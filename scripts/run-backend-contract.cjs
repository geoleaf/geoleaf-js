#!/usr/bin/env node
/**
 * Plays the server contract against a REAL bench — the two specs that speak to PostgREST
 * and pygeoapi rather than to a route.
 *
 * 🛑 ONE SCRIPT AND NOT AN INLINE `run:` BLOCK. The first draft inlined this orchestration
 * in `ci.yml`, and `verify-ci-parity.cjs` shredded it into eight nonsense leaves — each a
 * fragment of a JavaScript one-liner it was asked to keep in parity with `ci:local`. The
 * gate was right: a step whose body cannot be named cannot be declared. Here the step is
 * one leaf, with one entry in `DEFERRED_TO_E2E`.
 *
 * It is also what makes the runner's topology REPEATABLE ON THE WORKSTATION, which is the
 * only way to debug it without spending a remote run per attempt:
 *
 *     GEOLEAF_PG_PASSWORD=… GEOLEAF_JWT_SECRET=… node scripts/run-backend-contract.cjs
 *
 * Both secrets are generated when absent, and never leave the process that made them.
 */

const { execFileSync } = require("node:child_process");
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const COMPOSE = ["compose", "-f", "docker-compose.ci.yml"];

/**
 * 🛑 HTTPS, AND THE APPLICATION IS WHAT IMPOSES IT. The served page declares
 * `connect-src 'self' https:`; a bench in the clear on another origin satisfies neither
 * clause, and every `fetch` leaving the page answers "Failed to fetch" while Playwright's
 * own direct requests still pass — ten reds on exactly the tests that cross the page.
 * Measured on 20/09/2026. `ignoreHTTPSErrors` is global in `playwright.config.js`, so the
 * self-signed certificate the compose mints is accepted.
 */
const BENCH = process.env.GEOLEAF_BENCH_BASE_URL ?? "https://localhost:8099";

const env = {
    ...process.env,
    GEOLEAF_PG_PASSWORD: process.env.GEOLEAF_PG_PASSWORD || crypto.randomBytes(16).toString("hex"),
    GEOLEAF_JWT_SECRET: process.env.GEOLEAF_JWT_SECRET || crypto.randomBytes(32).toString("hex"),
    GEOLEAF_BENCH_BASE_URL: BENCH,
    // Read by `build-deploy.cjs` (which re-points the profile's bindings at the bench) AND
    // by the two specs, whose `API` is derived from it. One variable, one origin.
    GEOLEAF_BACKEND_BASE_URL: BENCH,
    // 🛑 `worker-budget.js` REFUSES to start beyond one worker while the variable above is
    // set: the three specs writing to the bench would write the same rows concurrently.
    GEOLEAF_E2E_WORKERS: "1",
};

/**
 * Runs a command, inheriting stdio so a failure is readable in the run's log.
 * @param {string} file
 * @param {string[]} args
 * @param {{ stdin?: string }} [opts]
 */
function run(file, args, opts = {}) {
    execFileSync(file, args, {
        cwd: ROOT,
        env,
        stdio: opts.stdin ? ["pipe", "inherit", "inherit"] : "inherit",
        input: opts.stdin ? fs.readFileSync(path.join(ROOT, opts.stdin)) : undefined,
    });
}

/**
 * Applies a SQL file as the owner role.
 *
 * 🛑 TWO PHASES, and the first is not optional: PostgREST and pygeoapi die if they start
 * before the schema has created their roles — `password authentication failed for user
 * "geoleaf_auth"` and a `ProviderConnectionError` that pygeoapi does not retry, since it
 * builds its OpenAPI at boot. The database's healthcheck says "accepts connections", never
 * "the schema exists", and no `depends_on` condition can carry that difference. Invisible
 * on the workstation, where the database has been seeded for weeks; a runner brings a NEW
 * one every run.
 * @param {string} file
 * @param {boolean} withPassword
 */
function psql(file, withPassword) {
    const args = [...COMPOSE, "exec", "-T"];
    if (withPassword) {
        args.push("-e", `PGOPTIONS=-c geoleaf.auth_password=${env.GEOLEAF_PG_PASSWORD}`);
    }
    args.push("postgis", "psql", "-U", "geoleaf_owner", "-d", "geoleaf", "-v", "ON_ERROR_STOP=1");
    run("docker", args, { stdin: file });
}

/** Writes the dev bootstrap the specs read to decide whether a bench exists. */
function writeConnector() {
    const b64 = (/** @type {object} */ o) => Buffer.from(JSON.stringify(o)).toString("base64url");
    const header = b64({ alg: "HS256", typ: "JWT" });
    const payload = b64({ role: "geoleaf_editor", exp: Math.floor(Date.now() / 1000) + 3600 });
    const signature = crypto
        .createHmac("sha256", env.GEOLEAF_JWT_SECRET)
        .update(`${header}.${payload}`)
        .digest("base64url");
    fs.writeFileSync(
        path.join(ROOT, "apps", "geoleaf-app", "connector.local.js"),
        `// Generated by scripts/run-backend-contract.cjs — DEV ONLY, git-ignored.\n` +
            `window.GEOLEAF_DEV_CONNECTOR = {\n` +
            `    baseUrl: ${JSON.stringify(BENCH)},\n` +
            `    getToken: async () => ${JSON.stringify(`${header}.${payload}.${signature}`)},\n` +
            `};\n`
    );
}

console.log(`── Contrat backend contre un vrai serveur — banc sur ${BENCH} ──\n`);

run("docker", [...COMPOSE, "up", "-d", "--wait", "postgis"]);
psql("docker/backend/01-schema.sql", true);
psql("docker/backend/02-seed.sql", false);
run("docker", [...COMPOSE, "up", "-d", "--wait"]);

writeConnector();

// ⚠️ The variant built here is DELIBERATELY NOT SHIPPABLE — `build-deploy.cjs` says so
// ("liaisons REPOINTÉES"). Nothing publishes it: no upload or deploy step follows.
run("npm", ["run", "build:deploy"], {});

// 🛑 `GEOLEAF_E2E_WORKERS=1` is not a tuning knob: `e2e/helpers/worker-budget.js` REFUSES
// to start beyond one worker while `GEOLEAF_BACKEND_BASE_URL` is set, because the three
// specs that write to the bench would write the same rows concurrently — an intermittent
// red that would be blamed on whichever commit is under test.
run(
    "npx",
    [
        "playwright",
        "test",
        "e2e/30-sync-cycle.spec.js",
        "e2e/31-delta-contract.spec.js",
        "--project=chromium",
    ],
    {}
);

console.log("\n✅ Contrat backend — les deux specs ont joué contre un vrai serveur.");
